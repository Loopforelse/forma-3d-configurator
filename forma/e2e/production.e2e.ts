import {test, expect} from '@playwright/test';

test('production assets, configuration, persistence, fresh links and PNG', async ({page, browser}, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => {if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`);});
  await page.goto('/');
  const png = page.getByRole('button', {name: 'Download PNG'});
  await expect(png).toBeEnabled();
  await expect(page.locator('canvas')).toBeVisible();
  const notices = await page.request.get('/THIRD_PARTY_NOTICES.txt');
  expect(notices.ok()).toBe(true);
  expect(await notices.text()).toContain('Permission is hereby granted');
  await page.getByRole('button', {name: 'Moss upholstery'}).click();
  await page.getByRole('button', {name: 'Soft leather'}).click();
  await page.getByRole('button', {name: 'Metal', exact: false}).click();
  await page.getByRole('button', {name: 'Brushed steel'}).click();
  await page.getByRole('checkbox').check();
  await expect(page.locator('.price strong')).toHaveText('$1,103.00');
  await page.getByLabel('Name this design').fill('Portfolio test');
  await page.getByRole('button', {name: 'Save design +'}).click();
  await page.reload();
  await expect(page.getByRole('heading', {name: 'Portfolio test'})).toBeVisible();
  await page.getByRole('button', {name: 'Load Portfolio test', exact: true}).click();
  await page.getByRole('button', {name: 'Share your design'}).click();
  const link = await page.getByLabel('Shareable design link').inputValue();
  const fresh = await browser.newContext();
  const shared = await fresh.newPage();
  await shared.goto(link);
  await expect(shared.locator('.price strong')).toHaveText('$1,103.00');
  await expect(shared.getByRole('button', {name: 'Moss upholstery'})).toHaveAttribute('aria-pressed', 'true');
  await expect(shared.getByRole('button', {name: 'Brushed steel'})).toHaveAttribute('aria-pressed', 'true');
  await expect(shared.getByRole('checkbox')).toBeChecked();
  await expect(shared.locator('.saved-grid article')).toHaveCount(0);
  const downloadPromise = shared.waitForEvent('download');
  await shared.getByRole('button', {name: 'Download PNG'}).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('forma-moss.png');
  const stream = await download.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(chunk);
  const image = Buffer.concat(chunks);
  expect(image.subarray(0,8).toString('hex')).toBe('89504e470d0a1a0a');
  expect(image.length).toBeGreaterThan(15000);
  await download.saveAs(testInfo.outputPath('forma-moss.png'));
  await shared.screenshot({path:testInfo.outputPath('desktop.png'),fullPage:true});
  await fresh.close();
  await page.goto('/portfolio/chair?v=1&color=__proto__');
  await expect(page.getByRole('status')).toContainText('invalid or outdated');
  await expect(page.locator('.price strong')).toHaveText('$649.00');
  expect(errors).toEqual([]);
});

test('mobile layout, touch rotation, pinch zoom and options', async ({browser}, testInfo) => {
  const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1,reducedMotion:'reduce'});
  const page = await context.newPage();
  await page.goto('/');
  await expect(page.getByRole('button', {name:'Download PNG'})).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const canvas = page.locator('canvas');
  const before = await canvas.screenshot();
  const box = (await canvas.boundingBox())!;
  const cdp = await context.newCDPSession(page);
  const x=box.x+box.width/2, y=box.y+box.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  for(let i=1;i<=8;i++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+i*10,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  const rotated=await canvas.screenshot();
  expect(rotated.equals(before)).toBe(false);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:0,x:x-30,y},{id:1,x:x+30,y}]});
  for(let i=1;i<=6;i++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{id:0,x:x-30-i*5,y},{id:1,x:x+30+i*5,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  expect((await canvas.screenshot()).equals(rotated)).toBe(false);
  expect(await page.evaluate(()=>visualViewport?.scale)).toBe(1);
  await page.getByRole('button',{name:'Clay upholstery'}).tap({timeout:4000});
  await page.getByRole('button',{name:'Soft leather'}).tap();
  await page.getByRole('checkbox').check();
  await expect(page.locator('.price strong')).toHaveText('$1,058.00');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('mobile.png'),fullPage:true});
  await context.close();
});

test('desktop drag, wheel zoom and camera presets render changes', async ({page}) => {
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/');
  await expect(page.getByRole('button',{name:'Download PNG'})).toBeEnabled();
  const canvas = page.locator('canvas');
  const before = await canvas.screenshot();
  const box = (await canvas.boundingBox())!;
  const x=box.x+box.width/2, y=box.y+box.height/2;
  await page.mouse.move(x,y);
  await page.mouse.down();
  await page.mouse.move(x+90,y+25,{steps:8});
  await page.mouse.up();
  const rotated=await canvas.screenshot();
  expect(rotated.equals(before)).toBe(false);
  await page.mouse.wheel(0,180);
  expect((await canvas.screenshot()).equals(rotated)).toBe(false);
  for(const view of ['front','side','rear']) {
    await page.getByRole('button',{name:view,exact:true}).click();
    await expect(page.getByRole('button',{name:view,exact:true})).toHaveAttribute('aria-pressed','true');
  }
  await page.getByRole('button',{name:'Reset view',exact:false}).click();
  await expect(page.getByRole('button',{name:'Auto rotate'})).toBeDisabled();
});
