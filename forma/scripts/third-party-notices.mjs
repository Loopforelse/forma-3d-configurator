// Run after dependency changes: node scripts/third-party-notices.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const sources = {
  '@react-three/fiber': 'https://raw.githubusercontent.com/pmndrs/react-three-fiber/master/LICENSE',
  maath: 'https://raw.githubusercontent.com/pmndrs/maath/main/LICENSE',
  '@mediapipe/tasks-vision': 'https://raw.githubusercontent.com/google-ai-edge/mediapipe/master/LICENSE',
  draco3d: 'https://raw.githubusercontent.com/google/draco/main/LICENSE',
};
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
let output = 'Forma third-party notices\n\nChair geometry and textures are generated by the application.\nThese notices cover the installed production dependency tree, including packages tree-shaken from the browser bundle. Versions are recorded in package-lock.json.\n';
for (const [location, entry] of Object.entries(lock.packages)) {
  if (!location || entry.dev) continue;
  const directory = path.join(root, location);
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
  output += `\n${'='.repeat(72)}\n${pkg.name} ${pkg.version} (${pkg.license || entry.license || 'see below'})\n`;
  const files = fs.readdirSync(directory).filter(name => /^(licen[sc]e|notice|copying)(\.|$|-)/i.test(name));
  if (files.length) {
    for (const name of files) output += `\n${name}\n${fs.readFileSync(path.join(directory, name), 'utf8')}\n`;
  } else if (pkg.name === 'stats-gl') {
    output += `\nLicense declared in package.json: MIT\nAuthor: ${JSON.stringify(pkg.author)}\nRepository: https://github.com/RenaudRohlinger/stats-gl\nNo standalone license file is distributed upstream. This unused diagnostic package is tree-shaken from Forma.\n`;
  } else {
    const url = sources[pkg.name];
    if (!url) throw Error(`No license source for ${pkg.name}`);
    const response = await fetch(url);
    if (!response.ok) throw Error(`License fetch failed: ${response.status} ${url}`);
    output += `\nSource: ${url}\n${await response.text()}\n`;
  }
}
fs.mkdirSync(path.join(root, 'public'), {recursive: true});
fs.writeFileSync(path.join(root, 'public/THIRD_PARTY_NOTICES.txt'), output);
